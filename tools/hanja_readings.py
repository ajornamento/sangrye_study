_DUEUM_IOTIZED = {"ㅑ", "ㅕ", "ㅖ", "ㅛ", "ㅠ", "ㅣ", "ㅒ"}


def _decompose(syl):
    code = ord(syl) - 0xAC00
    cho = code // 588
    jung = (code % 588) // 28
    jong = code % 28
    return cho, jung, jong


def _compose(cho, jung, jong):
    return chr(0xAC00 + cho * 588 + jung * 28 + jong)


def apply_dueum(syl):
    """단어 첫머리 두음법칙을 적용한 음절을 반환한다."""
    if not syl or not ("\uac00" <= syl <= "\ud7a3"):
        return syl
    cho, jung, jong = _decompose(syl)
    cho_ch = _CHOSEONG[cho]
    jung_ch = _JUNGSEONG[jung]
    if cho_ch == "ㄹ":
        if jung_ch in _DUEUM_IOTIZED:
            return _compose(11, jung, jong)  # ㅇ
        return _compose(2, jung, jong)       # ㄴ
    if cho_ch == "ㄴ" and jung_ch in {"ㅕ", "ㅛ", "ㅠ", "ㅣ"}:
        return _compose(11, jung, jong)      # ㅇ
    return syl


def is_cjk_char(ch):
    cp = ord(ch)
    return (0x3400 <= cp <= 0x9FFF) or (0xF900 <= cp <= 0xFAFF) or (0x20000 <= cp <= 0x2EBEF)


def compute_readings(raw_text, apply_word_initial=True):
    """원문 문자열(PAGE 토큰 포함 가능)에서 각 시작 인덱스별 (토큰길이, 독음) 사전을 계산한다."""
    tokens = []
    pos = 0
    n = len(raw_text)
    while pos < n:
        if raw_text[pos] == "\x00":
            m = PAGE_TOKEN_RE.match(raw_text, pos)
            if m:
                pos = m.end()
                continue
        m_ids = IDS_SEQ_RE.match(raw_text, pos)
        if m_ids:
            seq = m_ids.group(0)
            tokens.append((pos, seq, True))
            pos = m_ids.end()
            continue
        ch = raw_text[pos]
        tokens.append((pos, ch, is_cjk_char(ch)))
        pos += 1

    t_len = len(tokens)
    readings = [None] * t_len
    fixed = [False] * t_len
    i = 0
    while i < t_len:
        orig_pos, tok, is_hj = tokens[i]
        if not is_hj:
            i += 1
            continue
        matched = False
        if tok in _PHRASE_BY_FIRST:
            for phrase, pr_tuple in _PHRASE_BY_FIRST[tok]:
                plen = len(phrase)
                if i + plen <= t_len and all(tokens[i + k][1] == phrase[k] for k in range(plen)):
                    for k in range(plen):
                        readings[i + k] = pr_tuple[k]
                        fixed[i + k] = True
                    i += plen
                    matched = True
                    break
        if not matched:
            if tok in IDS_READINGS:
                readings[i] = IDS_READINGS[tok]
            else:
                readings[i] = CHAR_READINGS.get(tok, "")
            i += 1

    for idx in range(t_len):
        orig_pos, tok, is_hj = tokens[idx]
        if not is_hj or not readings[idx]:
            continue
        prev_is_hj = idx > 0 and tokens[idx - 1][2]
        if apply_word_initial and not prev_is_hj and not fixed[idx]:
            readings[idx] = apply_dueum(readings[idx])
        elif prev_is_hj and not fixed[idx] and readings[idx] in ("렬", "률"):
            prev_r = readings[idx - 1]
            if prev_r and ("\uac00" <= prev_r <= "\ud7a3"):
                _, _, p_jong = _decompose(prev_r)
                if p_jong in (0, 4):
                    readings[idx] = "열" if readings[idx] == "렬" else "율"

    for idx in range(t_len - 1):
        if tokens[idx][1] == "不" and not fixed[idx] and tokens[idx + 1][2]:
            nxt_r = readings[idx + 1]
            if nxt_r and ("\uac00" <= nxt_r <= "\ud7a3"):
                n_cho, _, _ = _decompose(nxt_r)
                if n_cho in (3, 12):
                    readings[idx] = "부"

    return {
        tokens[idx][0]: (len(tokens[idx][1]), readings[idx])
        for idx in range(t_len)
        if tokens[idx][2] and readings[idx]
    }


def plain_reading_string(text):
    """표제 등 짧은 한자 문자열의 전체 한글 독음 문자열을 반환한다."""
    rmap = compute_readings(text)
    out = []
    pos = 0
    n = len(text)
    while pos < n:
        if pos in rmap:
            tlen, r = rmap[pos]
            out.append(r)
            pos += tlen
        else:
            ch = text[pos]
            if ch not in "〈〉｛｝〔〕【】" and not ch.isspace():
                out.append(ch)
            pos += 1
    return "".join(out)
